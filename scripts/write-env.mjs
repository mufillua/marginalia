// Generates src/app/core/config/env.generated.ts from environment variables
// (or a local .env file) so no project URLs or keys live in source control.
//
//   SUPABASE_URL              https://<project-ref>.supabase.co        (required)
//   SUPABASE_PUBLISHABLE_KEY  sb_publishable_... or legacy anon key    (required)
//   GOOGLE_BOOKS_API_KEY      optional; raises the Google Books quota
//   ENABLE_GOOGLE_SIGN_IN     "true" once Google is enabled in Supabase Auth
//   SITE_URL                  production address, used for canonical links
//                             (default https://marginaliashelf.vercel.app)
//
// Never put a service-role / secret key here: everything in this file ships
// to the browser.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = resolve(root, '.env');

const fromFile = {};
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!match) continue;
    fromFile[match[1]] = match[2].replace(/^['"]|['"]$/g, '');
  }
}

const read = (name) => (process.env[name] ?? fromFile[name] ?? '').trim();

const config = {
  supabaseUrl: read('SUPABASE_URL').replace(/\/+$/, ''),
  supabasePublishableKey: read('SUPABASE_PUBLISHABLE_KEY'),
  googleBooksApiKey: read('GOOGLE_BOOKS_API_KEY'),
  enableGoogleSignIn: read('ENABLE_GOOGLE_SIGN_IN').toLowerCase() === 'true',
  siteUrl: (read('SITE_URL') || 'https://marginaliashelf.vercel.app').replace(/\/+$/, ''),
};

if (/service_role|sb_secret_/i.test(config.supabasePublishableKey)) {
  console.error('\n✖ SUPABASE_PUBLISHABLE_KEY looks like a secret/service-role key. Use the publishable key.\n');
  process.exit(1);
}

if (!config.supabaseUrl || !config.supabasePublishableKey) {
  console.warn(
    '\n⚠ SUPABASE_URL or SUPABASE_PUBLISHABLE_KEY is not set. The app will build, but it will show a setup screen until they are provided (see README).\n',
  );
}

const out = resolve(root, 'src/app/core/config/env.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/write-env.mjs — do not edit or commit.\nimport type { AppEnv } from './env';\n\nexport const generatedEnv: AppEnv = ${JSON.stringify(config, null, 2)};\n`,
);
console.log(`✓ Wrote ${out.replace(root + '/', '')}`);
